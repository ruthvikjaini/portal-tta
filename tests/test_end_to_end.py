import json
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def test_measured_json_matches_experiment_rows():
    measured = json.loads((ROOT / "results" / "measured.json").read_text())
    rows = json.loads((ROOT / "results" / "experiment.json").read_text())["rows"]
    assert measured["seeds"] == list(range(8))
    assert measured["n_batches"] == 12
    # Recompute one table cell from the rows and compare.
    cell_rows = [
        r
        for r in rows
        if r["scenario"] == "mixed_arrivals" and r["policy"] == "portal"
    ]
    assert len(cell_rows) == 8
    recomputed = float(np.mean([r["accuracy"] for r in cell_rows]))
    assert abs(recomputed - measured["table"]["mixed_arrivals"]["portal"]["accuracy"]) < 1e-9


def test_crossfoot_readme_contains_headline_values():
    measured = json.loads((ROOT / "results" / "measured.json").read_text())
    readme = (ROOT / "README.md").read_text()
    for key, value in measured["headline"].items():
        assert f"{value:.3f}" in readme, f"{key} = {value:.3f} missing from README"


def test_no_branding_or_watermark_phrases():
    banned = ["Muse", "AI-generated", "generated by Muse", "watermark"]
    # Scan shipped code and docs only: this test file itself names the
    # banned phrases as literals, and caches are not shipped content.
    roots = [
        ROOT / "src",
        ROOT / "scripts",
        ROOT / "docs",
        ROOT / "config",
        ROOT / "examples",
        ROOT / "README.md",
    ]
    for root in roots:
        files = [root] if root.is_file() else list(root.rglob("*"))
        for path in files:
            if path.is_dir():
                continue
            if "__pycache__" in str(path) or path.suffix == ".pyc":
                continue
            text = path.read_text(encoding="utf-8")
            for phrase in banned:
                assert phrase not in text, f"{phrase!r} found in {path}"


def test_demo_runs():
    out = subprocess.run(
        [sys.executable, "scripts/demo.py", "--n-batches", "3", "--seed", "0"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        env={"PYTHONPATH": "src", "PATH": "/usr/bin:/bin"},
    )
    assert out.returncode == 0, out.stderr
    assert "mean accuracy" in out.stdout
